#!/usr/bin/env node
/* Writes levels/manifest.js: the list of level files index.html loads and
   sw.js precaches. Every *.js under levels/wNN/ is a level, except names
   starting with "_" (drafts / templates).
     node tools/levels-manifest.mjs          rewrite the manifest
     node tools/levels-manifest.mjs --check  exit 1 if the manifest is stale
   (from app/: npm run levels / npm run levels:check) */
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const LEVELS = join(ROOT, 'levels');
const OUT = join(LEVELS, 'manifest.js');

export function levelFiles() {
  return readdirSync(LEVELS, { withFileTypes: true })
    .filter((d) => d.isDirectory() && /^w\d\d$/.test(d.name))
    .map((d) => d.name)
    .sort()
    .flatMap((w) => readdirSync(join(LEVELS, w))
      .filter((f) => f.endsWith('.js') && !f.startsWith('_'))
      .sort()
      .map((f) => `${w}/${f}`));
}

export function manifestSource(files) {
  return [
    '/* GENERATED by `node tools/levels-manifest.mjs` (from app/: `npm run levels`).',
    '   Every level file, in load order: index.html loads them and sw.js precaches',
    '   them. Do not hand-edit — add your level file, then re-run the generator. */',
    'self.KINAN_LEVEL_FILES = [',
    files.map((f) => `  '${f}'`).join(',\n'),
    '];',
    ''
  ].join('\n');
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const want = manifestSource(levelFiles());
  const have = existsSync(OUT) ? readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (process.argv.includes('--check')) {
    if (have !== want) { console.error('levels/manifest.js is stale — run: node tools/levels-manifest.mjs'); process.exit(1); }
    console.log('levels/manifest.js is up to date (' + levelFiles().length + ' level files)');
  } else {
    writeFileSync(OUT, want);
    console.log('wrote levels/manifest.js (' + levelFiles().length + ' level files)');
  }
}
